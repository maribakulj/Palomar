(ns palomar.plugins.lrmoo.prov-test
  "PROV-O export of computational provenance (audit S35)."
  (:require [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [palomar.convert :as convert]
            [palomar.curate]
            [palomar.plugins.lrmoo.ntriples :as nt]
            [palomar.plugins.lrmoo.prov :as prov]))

(def ^:private dc (slurp "test/fixtures/documentary/dublin-core/w3c_dc_example1.xml"))

(defn- wemi [] (first (:records (convert/to-wemi :dc {:record-id :dc/x} dc))))

(deftest every-assertion-is-a-reified-statement
  (let [r (wemi)]
    (is (= (count (:assertions r)) (prov/statement-count r)))))

(deftest a-statement-names-its-activity-rule-and-status
  (let [ts      (nt/parse (prov/->ntriples (wemi)))
        by-pred (group-by #(:iri (second %)) ts)
        pv      "http://www.w3.org/ns/prov#"]
    (testing "statements are generated by PROV activities: the engine (an Agent) carried them out, following the rule (a Plan)"
      (is (seq (by-pred (str pv "wasGeneratedBy"))))
      (is (some #(= {:iri (str pv "Activity")} (nth % 2)) ts))
      (is (some #(= {:iri (str pv "Plan")} (nth % 2)) ts))
      (is (some #(= {:iri (str pv "SoftwareAgent")} (nth % 2)) ts))
      (is (some #(str/includes? (:iri (nth % 2)) "rule.from-mapping/dc-title")
                (by-pred (str pv "hadPlan"))))
      (testing "and wasAssociatedWith names only agents (its range), never a rule"
        (is (every? #(= "urn:palomar:agent:engine" (:iri (nth % 2))) (by-pred (str pv "wasAssociatedWith"))))))
    (testing "the inferred WEMI claims say they are proposed, and derive from the record"
      (is (some #(= {:lit "proposed"} (nth % 2)) (by-pred "urn:palomar:vocab#status")))
      (is (seq (by-pred (str pv "wasDerivedFrom")))))))

(deftest the-prov-target-converts-and-parses
  (let [{:keys [output]} (convert/convert {:from :dc :to :prov :source dc :opts {:record-id :dc/x}})]
    (is (seq (nt/parse output)))))

(deftest a-statement-keeps-its-iri-through-curation
  (testing "the statement IRI is the assertion id, so accepting a claim does not rename it (ADR 0027)"
    (let [r        (wemi)
          accepted (first (:records (palomar.curate/curate [r] palomar.curate/accept-all)))
          stmts    (fn [rec] (set (keep #(when (= "http://www.w3.org/1999/02/22-rdf-syntax-ns#Statement" (:iri (nth % 2)))
                                           (:iri (first %)))
                                        (nt/parse (prov/->ntriples rec)))))]
      (is (= (stmts r) (stmts accepted))))))

(deftest a-curation-decision-is-a-prov-activity
  (testing "a rejection used and invalidated the statement, carried out by the curator, at its time (ADR 0028)"
    (let [r     (first (:records (palomar.curate/curate [(wemi)] palomar.curate/reject-all
                                                        {:by "curator-1" :at #inst "2026-10-25T12:00:00Z"})))
          ts    (nt/parse (prov/->ntriples r))
          by-p  (group-by #(:iri (second %)) ts)
          pv    "http://www.w3.org/ns/prov#"]
      (is (seq (by-p (str pv "wasInvalidatedBy"))))
      (is (seq (by-p (str pv "used"))))
      (is (some #(= "2026-10-25T12:00:00Z" (:lit (nth % 2))) (by-p (str pv "endedAtTime"))))
      (is (some #(= "curator-1" (:lit (nth % 2))) (by-p "urn:palomar:vocab#label"))))))
